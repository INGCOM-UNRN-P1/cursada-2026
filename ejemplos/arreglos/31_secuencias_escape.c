/* 31_secuencias_escape.c
 *
 * Las secuencias de escape representan caracteres especiales.
 */

#include <stdio.h>

int main(void)
{
    printf("Linea 1\n");
    printf("Linea 2\n");

    printf("Columna1\tColumna2\n");

    printf("Comilla doble: \"\n");
    printf("Comilla simple: \'\n");
    printf("Barra invertida: \\\n");

    return 0;
}
